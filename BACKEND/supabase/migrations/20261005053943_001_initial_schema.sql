-- ============================================================
-- 7. ACTIVITIES
-- ============================================================

CREATE TABLE public.activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,

    category TEXT,

    mapping_status TEXT NOT NULL DEFAULT 'official'
        CHECK (
            mapping_status IN (
                'official',
                'provisional',
                'deprecated'
            )
        ),

    source_version_id BIGINT
        REFERENCES public.source_versions(id),

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);


CREATE TABLE public.activity_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    activity_id BIGINT NOT NULL
        REFERENCES public.activities(id)
        ON DELETE CASCADE,

    alias TEXT NOT NULL,
    normalized_alias TEXT NOT NULL,

    status TEXT NOT NULL DEFAULT 'provisional'
        CHECK (
            status IN (
                'official',
                'provisional',
                'deprecated'
            )
        ),

    source_version_id BIGINT
        REFERENCES public.source_versions(id),

    notes TEXT,

    UNIQUE (
        activity_id,
        normalized_alias
    )
);


CREATE INDEX ix_activity_aliases_trgm
    ON public.activity_aliases
    USING GIN (normalized_alias extensions.gin_trgm_ops);


-- ============================================================
-- 8. PROCEDURES
-- ============================================================

CREATE TABLE public.procedures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,

    description TEXT,

    source_version_id BIGINT
        REFERENCES public.source_versions(id),

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);


CREATE TABLE public.activity_procedures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    activity_id BIGINT NOT NULL
        REFERENCES public.activities(id)
        ON DELETE CASCADE,

    procedure_id BIGINT NOT NULL
        REFERENCES public.procedures(id)
        ON DELETE CASCADE,

    source_version_id BIGINT NOT NULL
        REFERENCES public.source_versions(id),

    priority INTEGER NOT NULL DEFAULT 100,

    notes TEXT,

    UNIQUE (
        activity_id,
        procedure_id,
        source_version_id
    )
);


CREATE TABLE public.procedure_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    activity_procedure_id BIGINT
        REFERENCES public.activity_procedures(id)
        ON DELETE CASCADE,

    procedure_id BIGINT
        REFERENCES public.procedures(id)
        ON DELETE CASCADE,

    source_version_id BIGINT NOT NULL
        REFERENCES public.source_versions(id),

    rule_type TEXT NOT NULL,

    priority INTEGER NOT NULL DEFAULT 100,

    min_surface_m2 NUMERIC,
    max_surface_m2 NUMERIC,

    conditions JSONB NOT NULL DEFAULT '{}'::jsonb,

    rationale TEXT,

    active BOOLEAN NOT NULL DEFAULT TRUE,

    CHECK (
        activity_procedure_id IS NOT NULL
        OR procedure_id IS NOT NULL
    )
);


CREATE TABLE public.procedure_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    procedure_id BIGINT NOT NULL
        REFERENCES public.procedures(id)
        ON DELETE CASCADE,

    requirement_code TEXT,

    title TEXT NOT NULL,
    description TEXT,

    conditional BOOLEAN NOT NULL DEFAULT FALSE,

    conditions JSONB NOT NULL DEFAULT '{}'::jsonb,

    source_version_id BIGINT
        REFERENCES public.source_versions(id)
);


CREATE TABLE public.procedure_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    procedure_id BIGINT NOT NULL
        REFERENCES public.procedures(id)
        ON DELETE CASCADE,

    document_code TEXT,

    title TEXT NOT NULL,
    description TEXT,

    conditional BOOLEAN NOT NULL DEFAULT FALSE,

    conditions JSONB NOT NULL DEFAULT '{}'::jsonb,

    source_version_id BIGINT
        REFERENCES public.source_versions(id)
);


CREATE TABLE public.procedure_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    procedure_id BIGINT NOT NULL
        REFERENCES public.procedures(id)
        ON DELETE CASCADE,

    step_order INTEGER NOT NULL,

    title TEXT NOT NULL,
    description TEXT,

    source_version_id BIGINT
        REFERENCES public.source_versions(id),

    UNIQUE (
        procedure_id,
        step_order
    )
);


-- ============================================================
-- 9. DOCUMENTS / RAG
-- ============================================================

CREATE TABLE public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_version_id BIGINT NOT NULL
        REFERENCES public.source_versions(id),

    document_key TEXT NOT NULL,

    title TEXT NOT NULL,

    uri TEXT,
    mime_type TEXT,

    page_count INTEGER,

    checksum_sha256 TEXT,

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    UNIQUE (
        source_version_id,
        document_key
    )
);


CREATE TABLE public.document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    document_id BIGINT NOT NULL
        REFERENCES public.documents(id)
        ON DELETE CASCADE,

    chunk_index INTEGER NOT NULL,

    content TEXT NOT NULL,

    heading_path TEXT,

    page_from INTEGER,
    page_to INTEGER,

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    content_tsv TSVECTOR
        GENERATED ALWAYS AS (
            to_tsvector('spanish', content)
        )
        STORED,

    embedding extensions.vector(1024),

    embedding_model_id BIGINT
        REFERENCES public.ai_models(id),

    embedded_at TIMESTAMPTZ,

    UNIQUE (
        document_id,
        chunk_index
    )
);


CREATE INDEX ix_document_chunks_tsv
    ON public.document_chunks
    USING GIN (content_tsv);


CREATE INDEX ix_document_chunks_embedding
    ON public.document_chunks
    USING HNSW (
        embedding extensions.vector_cosine_ops
    );


CREATE INDEX ix_document_chunks_metadata
    ON public.document_chunks
    USING GIN (metadata);


-- ============================================================
-- 10. QUERY TRACEABILITY
-- ============================================================

CREATE TABLE public.query_runs (
    id UUID PRIMARY KEY
        DEFAULT extensions.gen_random_uuid(),

    request_id UUID,

    question TEXT NOT NULL,

    activity_input TEXT,
    normalized_activity TEXT,

    address_input TEXT,
    normalized_address TEXT,

    street_code INTEGER,

    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,

    smp TEXT,

    chat_model_id BIGINT
        REFERENCES public.ai_models(id),

    embedding_model_id BIGINT
        REFERENCES public.ai_models(id),

    status TEXT NOT NULL
        CHECK (
            status IN (
                'started',
                'completed',
                'partial',
                'failed'
            )
        ),

    response_text TEXT,

    error_code TEXT,
    error_message TEXT,

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);


CREATE INDEX ix_query_runs_started
    ON public.query_runs (started_at DESC);


CREATE TABLE public.query_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    query_run_id UUID NOT NULL
        REFERENCES public.query_runs(id)
        ON DELETE CASCADE,

    evidence_type TEXT NOT NULL,

    reference_key TEXT NOT NULL,

    document_chunk_id BIGINT
        REFERENCES public.document_chunks(id),

    score DOUBLE PRECISION,

    source_version_id BIGINT
        REFERENCES public.source_versions(id),

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);


CREATE INDEX ix_query_evidence_query
    ON public.query_evidence (query_run_id);
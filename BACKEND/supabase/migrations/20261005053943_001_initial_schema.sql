-- ============================================================
-- 1. SOURCE CATALOG
-- ============================================================

CREATE TABLE public.sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    publisher TEXT,
    canonical_url TEXT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE TABLE public.source_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL
        REFERENCES public.sources(id),

    version_label TEXT NOT NULL,
    checksum_sha256 TEXT,

    published_at DATE,
    effective_from DATE,
    effective_to DATE,

    status TEXT NOT NULL DEFAULT 'ingested'
        CHECK (
            status IN (
                'ingested',
                'active',
                'superseded',
                'invalid'
            )
        ),

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (source_id, version_label)
);


CREATE TABLE public.source_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_version_id BIGINT NOT NULL
        REFERENCES public.source_versions(id)
        ON DELETE CASCADE,

    resource_type TEXT NOT NULL,
    uri TEXT NOT NULL,

    checksum_sha256 TEXT,
    retrieved_at TIMESTAMPTZ,

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);


-- ============================================================
-- 2. AI MODELS
-- ============================================================

CREATE TABLE public.ai_models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    provider TEXT NOT NULL,
    model_name TEXT NOT NULL,

    model_type TEXT NOT NULL
        CHECK (
            model_type IN (
                'embedding',
                'chat',
                'reranker'
            )
        ),

    dimension INTEGER,

    is_active BOOLEAN NOT NULL DEFAULT FALSE,

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    UNIQUE (
        provider,
        model_name,
        model_type
    )
);


-- ============================================================
-- 3. USIG GEOCODING CACHE
-- ============================================================

CREATE TABLE public.geocoding_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    query_key TEXT NOT NULL,

    input_address TEXT NOT NULL,

    normalized_street TEXT,
    street_code INTEGER,
    height INTEGER,

    gkba_x DOUBLE PRECISION,
    gkba_y DOUBLE PRECISION,

    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,

    smp TEXT,

    provider TEXT NOT NULL,
    provider_version TEXT,

    useful_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    adjacent_streets JSONB NOT NULL DEFAULT '[]'::jsonb,
    reverse_geocoding JSONB NOT NULL DEFAULT '{}'::jsonb,
    response_json JSONB NOT NULL DEFAULT '{}'::jsonb,

    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,

    UNIQUE (query_key, provider)
);


CREATE INDEX ix_geocoding_cache_smp
    ON public.geocoding_cache (smp);


-- ============================================================
-- 4. PARCELS / POSTGIS
-- ============================================================

CREATE TABLE public.parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    smp TEXT NOT NULL UNIQUE,

    geometry extensions.geometry(MultiPolygon, 4326),

    source_version_id BIGINT
        REFERENCES public.source_versions(id),

    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE INDEX ix_parcels_geometry
    ON public.parcels
    USING GIST (geometry);



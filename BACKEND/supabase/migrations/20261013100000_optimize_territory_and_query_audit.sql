-- SGI v0.3.0: esquema territorial compacto y persistencia del flujo determinista.
-- Migración de consolidación para instalaciones existentes: preserva los datos copiados,
-- pero elimina columnas legacy al final. Backup + staging obligatorio antes de aplicarla.
-- NO ejecutar como sustituto del historial de migraciones de Supabase.
BEGIN;
SET search_path = public, extensions;

-- 1. Atributos catastrales, sin duplicar la comuna (se deriva por barrio -> comuna).
ALTER TABLE public.parcels
    ADD COLUMN IF NOT EXISTS seccion TEXT,
    ADD COLUMN IF NOT EXISTS manzana TEXT,
    ADD COLUMN IF NOT EXISTS parcela TEXT;

-- 2. Geometría fuera del catálogo catastral: una geometría vigente por parcela.
-- No asignar/transformar un CRS desconocido automáticamente: abortar y corregir
-- el dataset en origen antes de continuar si hay geometrías que no son EPSG:4326.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema='public' AND table_name='parcels' AND column_name='geometry'
    ) AND EXISTS (SELECT 1 FROM public.parcels WHERE geometry IS NOT NULL AND ST_SRID(geometry) <> 4326) THEN
        RAISE EXCEPTION 'parcels.geometry contiene SRID distinto de 4326; reproyectar/validar antes de la migración';
    END IF;
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema='public' AND table_name='parcels' AND column_name='geom'
    ) AND EXISTS (SELECT 1 FROM public.parcels WHERE geom IS NOT NULL AND ST_SRID(geom) <> 4326) THEN
        RAISE EXCEPTION 'parcels.geom contiene SRID distinto de 4326; reproyectar/validar antes de la migración';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.parcel_geometries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id BIGINT NOT NULL UNIQUE
        REFERENCES public.parcels(id) ON DELETE CASCADE,
    geom geometry(MultiPolygon, 4326) NOT NULL,
    source_version_id BIGINT NOT NULL
        REFERENCES public.source_versions(id),
    checksum_sha256 TEXT,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (NOT ST_IsEmpty(geom))
);
CREATE INDEX IF NOT EXISTS ix_parcel_geometries_geom
    ON public.parcel_geometries USING GIST (geom);
CREATE INDEX IF NOT EXISTS ix_parcel_geometries_source
    ON public.parcel_geometries (source_version_id);

-- Los distritos también se versionan. La restricción heredada por (parcela, código)
-- impedía importar una nueva versión mientras quedara una fila histórica; sustituirla
-- por unicidad dentro de cada versión conserva trazabilidad sin duplicar un snapshot.
ALTER TABLE public.parcel_special_districts
    DROP CONSTRAINT IF EXISTS parcel_special_districts_parcel_id_group_code_special_code_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_parcel_special_districts_versioned_code
    ON public.parcel_special_districts (
        parcel_id, source_version_id,
        COALESCE(group_code, ''), COALESCE(special_code, '')
    );

-- Migrar cualquier geometría previa antes de quitarla de parcels.
-- La carga/caché geométrica posterior usa parcel_geometries como única fuente.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema='public' AND table_name='parcels' AND column_name='geometry'
    ) THEN
        EXECUTE $m$
            INSERT INTO public.parcel_geometries(parcel_id, geom, source_version_id, loaded_at)
            SELECT p.id,
                   ST_Multi(ST_CollectionExtract(ST_MakeValid(ST_Force2D(p.geometry)), 3))::geometry(MultiPolygon,4326),
                   p.source_version_id, now()
            FROM public.parcels p
            WHERE p.geometry IS NOT NULL
              AND NOT ST_IsEmpty(p.geometry)
              AND NOT ST_IsEmpty(ST_CollectionExtract(ST_MakeValid(ST_Force2D(p.geometry)), 3))
            ON CONFLICT (parcel_id) DO NOTHING
        $m$;
        DROP INDEX IF EXISTS public.ix_parcels_geometry;
        ALTER TABLE public.parcels DROP COLUMN geometry;
    ELSIF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema='public' AND table_name='parcels' AND column_name='geom'
    ) THEN
        EXECUTE $m$
            INSERT INTO public.parcel_geometries(parcel_id, geom, source_version_id, loaded_at)
            SELECT p.id,
                   ST_Multi(ST_CollectionExtract(ST_MakeValid(ST_Force2D(p.geom)), 3))::geometry(MultiPolygon,4326),
                   p.source_version_id, now()
            FROM public.parcels p
            WHERE p.geom IS NOT NULL
              AND NOT ST_IsEmpty(p.geom)
              AND NOT ST_IsEmpty(ST_CollectionExtract(ST_MakeValid(ST_Force2D(p.geom)), 3))
            ON CONFLICT (parcel_id) DO NOTHING
        $m$;
        ALTER TABLE public.parcels DROP COLUMN geom;
    END IF;
END $$;

-- 3. Columnas parcelarias auxiliares que también consume ingest_codigo_urbanistico.py.
-- Los flags se preservan como SMALLINT 0/1 (catalogado admite 0/1/2); el repositorio
-- los expone como valores originales sin reinterpretar su semántica jurídica.
ALTER TABLE public.urban_parcel_rules
    ADD COLUMN IF NOT EXISTS sm TEXT,
    ADD COLUMN IF NOT EXISTS catalogado SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS rh SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS ensanche SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS apertura SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS lep SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS ci_digital SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS anac SMALLINT NOT NULL DEFAULT 0;

DO $$
DECLARE
    flag_column TEXT;
    data_type_name TEXT;
BEGIN
    SELECT data_type INTO data_type_name
    FROM information_schema.columns
    WHERE table_schema='public' AND table_name='urban_parcel_rules' AND column_name='catalogado';
    IF data_type_name IN ('smallint', 'integer', 'bigint')
       AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.urban_parcel_rules'::regclass AND conname='ck_urban_parcel_rules_catalogado') THEN
        ALTER TABLE public.urban_parcel_rules ADD CONSTRAINT ck_urban_parcel_rules_catalogado
            CHECK (catalogado IS NULL OR catalogado BETWEEN 0 AND 2);
    END IF;

    FOREACH flag_column IN ARRAY ARRAY['rh','ensanche','apertura','lep','ci_digital','anac'] LOOP
        SELECT data_type INTO data_type_name
        FROM information_schema.columns
        WHERE table_schema='public' AND table_name='urban_parcel_rules' AND column_name=flag_column;
        IF data_type_name IN ('smallint', 'integer', 'bigint') THEN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conrelid='public.urban_parcel_rules'::regclass
                  AND conname=('ck_urban_parcel_rules_' || flag_column)
            ) THEN
                EXECUTE format(
                    'ALTER TABLE public.urban_parcel_rules ADD CONSTRAINT %I CHECK (%I IS NULL OR %I IN (0,1))',
                    'ck_urban_parcel_rules_' || flag_column, flag_column, flag_column
                );
            END IF;
        END IF;
    END LOOP;
END $$;

-- Mixturas normalizadas en una única columna. Mantiene compatibilidad de origen durante la conversión.
ALTER TABLE public.urban_parcel_rules
    ADD COLUMN IF NOT EXISTS mixturas SMALLINT[] NOT NULL DEFAULT ARRAY[]::SMALLINT[];
DO $$
DECLARE
    has_uso_1 BOOLEAN;
    has_uso_2 BOOLEAN;
    has_uso_3 BOOLEAN;
BEGIN
    SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='urban_parcel_rules' AND column_name='uso_1') INTO has_uso_1;
    SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='urban_parcel_rules' AND column_name='uso_2') INTO has_uso_2;
    SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='urban_parcel_rules' AND column_name='uso_3') INTO has_uso_3;
    IF has_uso_1 OR has_uso_2 OR has_uso_3 THEN
        UPDATE public.urban_parcel_rules upr
        SET mixturas = ARRAY(
            SELECT DISTINCT u::SMALLINT
            FROM unnest(ARRAY[
                CASE WHEN has_uso_1 THEN NULLIF(to_jsonb(upr)->>'uso_1','')::SMALLINT ELSE NULL END,
                CASE WHEN has_uso_2 THEN NULLIF(to_jsonb(upr)->>'uso_2','')::SMALLINT ELSE NULL END,
                CASE WHEN has_uso_3 THEN NULLIF(to_jsonb(upr)->>'uso_3','')::SMALLINT ELSE NULL END
            ]) AS valueset(u)
            WHERE u BETWEEN 1 AND 4
            ORDER BY u
        )
        WHERE cardinality(upr.mixturas) = 0;
    END IF;
END $$;
ALTER TABLE public.urban_parcel_rules
    DROP CONSTRAINT IF EXISTS urban_parcel_rules_uso_1_check,
    DROP CONSTRAINT IF EXISTS urban_parcel_rules_uso_2_check,
    DROP CONSTRAINT IF EXISTS urban_parcel_rules_uso_3_check;
ALTER TABLE public.urban_parcel_rules
    DROP COLUMN IF EXISTS uso_1,
    DROP COLUMN IF EXISTS uso_2,
    DROP COLUMN IF EXISTS uso_3;
ALTER TABLE public.urban_parcel_rules
    DROP CONSTRAINT IF EXISTS ck_urban_parcel_rules_mixturas,
    ADD CONSTRAINT ck_urban_parcel_rules_mixturas
    CHECK (
        cardinality(mixturas) <= 3
        AND mixturas <@ ARRAY[1,2,3,4]::SMALLINT[]
        AND array_position(mixturas, NULL::SMALLINT) IS NULL
    );

-- 4. Variantes/modalidades de los procedimientos (DDRR, licencia, exprés).
-- La clasificación de Anexo II sigue separada; procedure_variants conecta el tipo
-- documentado con los requisitos/pasos propios del procedimiento.
CREATE TABLE IF NOT EXISTS public.procedure_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL REFERENCES public.procedures(id) ON DELETE CASCADE,
    code TEXT NOT NULL CHECK (code IN ('DDRR_E', 'DDRR_SP', 'DDRR_CP', 'LICENCIA')),
    name TEXT NOT NULL,
    description TEXT,
    conditions JSONB NOT NULL DEFAULT '{}'::JSONB,
    immediate_start_allowed BOOLEAN,
    prior_inspection_required BOOLEAN,
    validity_years SMALLINT CHECK (validity_years IS NULL OR validity_years > 0),
    source_version_id BIGINT NOT NULL REFERENCES public.source_versions(id),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (procedure_id, code)
);
CREATE INDEX IF NOT EXISTS ix_procedure_variants_code_active
    ON public.procedure_variants (code) WHERE active = TRUE;
CREATE INDEX IF NOT EXISTS ix_procedure_variants_procedure
    ON public.procedure_variants (procedure_id) WHERE active = TRUE;

-- 5. Auditoría del flujo inicial, independiente de que se utilice IA.
ALTER TABLE public.query_runs
    ADD COLUMN IF NOT EXISTS request_payload JSONB NOT NULL DEFAULT '{}'::JSONB,
    ADD COLUMN IF NOT EXISTS response_json JSONB,
    ADD COLUMN IF NOT EXISTS execution_mode TEXT NOT NULL DEFAULT 'legacy';
ALTER TABLE public.query_runs
    DROP CONSTRAINT IF EXISTS ck_query_runs_execution_mode,
    ADD CONSTRAINT ck_query_runs_execution_mode
    CHECK (execution_mode IN ('legacy', 'deterministic', 'ai_assisted'));
CREATE INDEX IF NOT EXISTS ix_query_runs_status_started
    ON public.query_runs(status, started_at DESC);

COMMENT ON TABLE public.parcel_geometries IS
    'Caché geométrica vigente por parcela. No almacenar la geometría en parcels.';
COMMENT ON COLUMN public.urban_parcel_rules.mixturas IS
    'Mixturas urbanísticas disponibles (1..4), normalizadas en una lista ordenada.';
COMMENT ON TABLE public.procedure_variants IS
    'Modalidades de trámite vinculadas a los códigos documentados en el Anexo II; las condiciones se preservan en JSONB.';
COMMENT ON COLUMN public.query_runs.response_json IS
    'Respuesta estructurada íntegra del endpoint, para auditoría, debugging y análisis determinista.';
COMMENT ON COLUMN public.query_runs.request_payload IS
    'Entrada estructurada recibida por el flujo, incluida la separación dirección/actividad/parámetros.';
COMMIT;

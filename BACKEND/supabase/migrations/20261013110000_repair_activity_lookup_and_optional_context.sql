-- Reparaciones aditivas para el flujo territorial del MVP.
-- No borra ni reescribe parcelas, reglas ni mapeos legales existentes.
BEGIN;
SET search_path = public, extensions;

-- 1. Alias coloquial provisional para que "cafetería" pueda mapearse a la actividad
-- de catálogo 1.5. Se mantiene provisional: no convierte la sugerencia en una decisión
-- jurídica confirmada. Se prioriza la versión activa del Anexo II como trazabilidad.
WITH target_activity AS (
    SELECT id, source_version_id
    FROM public.activities
    WHERE code = '1.5' AND mapping_status <> 'deprecated'
    ORDER BY id
    LIMIT 1
), alias_source AS (
    SELECT sv.id
    FROM public.source_versions sv
    JOIN public.sources s ON s.id = sv.source_id
    WHERE s.code = 'resolucion_96_agc_25_anexo_ii'
      AND sv.status IN ('active', 'ingested')
    ORDER BY (sv.status = 'active') DESC,
             COALESCE(sv.effective_from, sv.published_at) DESC NULLS LAST,
             sv.id DESC
    LIMIT 1
)
INSERT INTO public.activity_aliases (
    activity_id, alias, normalized_alias, status, source_version_id
)
SELECT ta.id, 'cafetería', 'cafeteria', 'provisional',
       COALESCE((SELECT id FROM alias_source), ta.source_version_id)
FROM target_activity ta
ON CONFLICT (activity_id, normalized_alias) DO UPDATE
SET alias = EXCLUDED.alias,
    status = CASE
        WHEN public.activity_aliases.status = 'official' THEN 'official'
        ELSE 'provisional'
    END,
    source_version_id = EXCLUDED.source_version_id;

-- 2. Alinear procedure_variants con el contrato actual. El código también tolera
-- despliegues legacy que aún no tengan active.
ALTER TABLE public.procedure_variants
    ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;

-- 3. La tabla puede faltar en despliegues que aplicaron la migración compacta pero no
-- la inicial. La creamos de forma aditiva; importar observaciones reales es otro paso.
CREATE TABLE IF NOT EXISTS public.land_use_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_record_id BIGINT NOT NULL,
    parcel_id BIGINT REFERENCES public.parcels(id) ON DELETE SET NULL,
    source_version_id BIGINT NOT NULL REFERENCES public.source_versions(id),
    tipo1 TEXT,
    tipo2 TEXT,
    estado TEXT,
    pisos TEXT,
    obs TEXT,
    anio SMALLINT,
    geometry geometry(Point, 4326),
    UNIQUE (source_version_id, source_record_id)
);
CREATE INDEX IF NOT EXISTS ix_land_use_observations_parcel_year
    ON public.land_use_observations(parcel_id, anio DESC NULLS LAST);
CREATE INDEX IF NOT EXISTS ix_land_use_observations_geometry
    ON public.land_use_observations USING GIST(geometry);

COMMIT;

-- ============================================================================
-- SGI - SCHEMA MVP FINAL
-- Sistema de Gestión Inteligente - CABA
--
-- Objetivo:
--   Modelo mínimo y suficiente para el MVP:
--     ubicación -> parcela/SMP -> normativa territorial -> actividad ->
--     compatibilidad urbanística -> trámites/requisitos -> evidencia/RAG
--
-- Principios:
--   * una sola representación territorial canónica: parcels.id + smp UNIQUE
--   * no repetir SMP, sección/manzana/parcela, barrio o comuna en tablas hijas
--   * mantener solo campos utilizados por el análisis o por relaciones futuras
--   * conservar proveniencia mediante source_versions/resources
--   * los archivos originales (GeoJSON, CSV, XLSX, PDF) viven fuera de PostgreSQL
--   * estado normalizado ACTUAL en la DB; el histórico completo de archivos queda
--     fuera de la DB. Se agrega historial normalizado solo si el MVP lo requiere.
--   * índices solo donde existe una consulta/relación real que lo justifique
--
-- IMPORTANTE:
--   Este archivo es un BASELINE para una BD NUEVA / reconstruible.
--   NO ejecutar sobre una BD con datos que deban conservarse.
-- ============================================================================

BEGIN;

SET search_path = public, extensions;

-- --------------------------------------------------------------------------
-- 0. EXTENSIONES
-- --------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- --------------------------------------------------------------------------
-- 1. RESET DEL MODELO DE APLICACIÓN
-- --------------------------------------------------------------------------
-- No elimina auth/storage ni objetos internos de Supabase.
DROP TABLE IF EXISTS query_evidence CASCADE;
DROP TABLE IF EXISTS query_runs CASCADE;
DROP TABLE IF EXISTS document_chunks CASCADE;
DROP TABLE IF EXISTS documents CASCADE;
DROP TABLE IF EXISTS procedure_steps CASCADE;
DROP TABLE IF EXISTS procedure_documents CASCADE;
DROP TABLE IF EXISTS procedure_requirements CASCADE;
DROP TABLE IF EXISTS procedure_rules CASCADE;
DROP TABLE IF EXISTS activity_procedures CASCADE;
DROP TABLE IF EXISTS activity_use_rules CASCADE;
DROP TABLE IF EXISTS activity_aliases CASCADE;
DROP TABLE IF EXISTS activities CASCADE;
DROP TABLE IF EXISTS geocoding_cache CASCADE;
DROP TABLE IF EXISTS land_use_observations CASCADE;
DROP TABLE IF EXISTS parcel_special_districts CASCADE;
DROP TABLE IF EXISTS urban_parcel_rules CASCADE;
DROP TABLE IF EXISTS parcels CASCADE;
DROP TABLE IF EXISTS barrios CASCADE;
DROP TABLE IF EXISTS comunas CASCADE;
DROP TABLE IF EXISTS ai_models CASCADE;
DROP TABLE IF EXISTS source_resources CASCADE;
DROP TABLE IF EXISTS source_versions CASCADE;
DROP TABLE IF EXISTS sources CASCADE;

-- --------------------------------------------------------------------------
-- 2. FUENTES Y VERSIONES
-- --------------------------------------------------------------------------
CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    publisher TEXT,
    canonical_url TEXT
);

CREATE TABLE source_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL
        REFERENCES sources(id),
    version_label TEXT NOT NULL,
    checksum_sha256 TEXT,
    published_at DATE,
    effective_from DATE,
    effective_to DATE,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'superseded', 'invalid', 'ingested')),
    UNIQUE (source_id, version_label),
    CHECK (
        effective_from IS NULL
        OR effective_to IS NULL
        OR effective_from <= effective_to
    )
);

CREATE INDEX ix_source_versions_source
    ON source_versions(source_id);

CREATE UNIQUE INDEX uq_source_versions_active
    ON source_versions(source_id)
    WHERE status = 'active';

CREATE TABLE source_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id)
        ON DELETE CASCADE,
    resource_type TEXT NOT NULL,
    uri TEXT NOT NULL,
    mime_type TEXT,
    size_bytes BIGINT,
    checksum_sha256 TEXT,
    retrieved_at TIMESTAMPTZ,
    UNIQUE (source_version_id, uri)
);

CREATE INDEX ix_source_resources_version
    ON source_resources(source_version_id);

-- --------------------------------------------------------------------------
-- 3. DIMENSIONES TERRITORIALES
-- --------------------------------------------------------------------------
-- Son catálogos pequeños: 15 comunas / 48 barrios aprox.
-- Evitan repetir texto en cada parcela.
CREATE TABLE comunas (
    id SMALLINT PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE barrios (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    comuna_id SMALLINT NOT NULL
        REFERENCES comunas(id)
);

CREATE INDEX ix_barrios_comuna
    ON barrios(comuna_id);

-- --------------------------------------------------------------------------
-- 4. PARCELAS: IDENTIDAD TERRITORIAL CANÓNICA
-- --------------------------------------------------------------------------
-- SMP es la clave territorial de integración.
-- NO se repiten seccion/manzana/parcela en otras tablas.
CREATE TABLE parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    smp TEXT NOT NULL UNIQUE,
    partida_ma BIGINT,
    barrio_id SMALLINT
        REFERENCES barrios(id),
    geometry geometry(MultiPolygon, 4326),
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id)
);

CREATE INDEX ix_parcels_geometry
    ON parcels USING GIST(geometry);

CREATE INDEX ix_parcels_barrio
    ON parcels(barrio_id)
    WHERE barrio_id IS NOT NULL;

CREATE INDEX ix_parcels_partida_ma
    ON parcels(partida_ma)
    WHERE partida_ma IS NOT NULL;

-- --------------------------------------------------------------------------
-- 5. REGLA URBANÍSTICA DE LA PARCELA
-- --------------------------------------------------------------------------
-- Solo los datos necesarios para determinar la compatibilidad con el
-- Cuadro de Usos 3.3 y reconocer distritos especiales.
--
-- Se mantiene SOLO la versión normalizada vigente en la DB.
-- La versión histórica completa permanece en el archivo fuente externo.
CREATE TABLE urban_parcel_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id BIGINT NOT NULL UNIQUE
        REFERENCES parcels(id)
        ON DELETE CASCADE,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    uso_1 SMALLINT,
    uso_2 SMALLINT,
    uso_3 SMALLINT,
    CHECK (uso_1 IS NULL OR uso_1 BETWEEN 1 AND 4),
    CHECK (uso_2 IS NULL OR uso_2 BETWEEN 1 AND 4),
    CHECK (uso_3 IS NULL OR uso_3 BETWEEN 1 AND 4)
);

CREATE TABLE parcel_special_districts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id BIGINT NOT NULL
        REFERENCES parcels(id)
        ON DELETE CASCADE,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    group_code TEXT,
    special_code TEXT,
    CHECK (group_code IS NOT NULL OR special_code IS NOT NULL),
    UNIQUE (parcel_id, group_code, special_code)
);

-- --------------------------------------------------------------------------
-- 6. USOS DEL SUELO OBSERVADOS
-- --------------------------------------------------------------------------
-- Información contextual, no fuente normativa de compatibilidad.
CREATE TABLE land_use_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_record_id BIGINT NOT NULL,
    parcel_id BIGINT
        REFERENCES parcels(id)
        ON DELETE SET NULL,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    tipo1 TEXT,
    tipo2 TEXT,
    estado TEXT,
    pisos TEXT,
    obs TEXT,
    anio SMALLINT,
    geometry geometry(Point, 4326),
    UNIQUE (source_version_id, source_record_id)
);

CREATE INDEX ix_land_use_observations_parcel_year
    ON land_use_observations(parcel_id, anio DESC NULLS LAST);

CREATE INDEX ix_land_use_observations_geometry
    ON land_use_observations USING GIST(geometry);

-- --------------------------------------------------------------------------
-- 7. CACHE DE GEOCODIFICACIÓN
-- --------------------------------------------------------------------------
-- Es un cache operacional de USIG, no una segunda fuente territorial.
-- 'smp' conserva el resultado del proveedor aunque todavía no exista una
-- parcela cargada; 'resolved_parcel_id' es la relación interna cuando existe.
CREATE TABLE geocoding_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_key TEXT NOT NULL,
    input_address TEXT NOT NULL,
    normalized_street TEXT,
    street_code INTEGER,
    height INTEGER,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    smp TEXT,
    resolved_parcel_id BIGINT
        REFERENCES parcels(id)
        ON DELETE SET NULL,
    response_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    UNIQUE (source_version_id, query_key)
);

CREATE INDEX ix_geocoding_cache_expires
    ON geocoding_cache(expires_at)
    WHERE expires_at IS NOT NULL;

CREATE INDEX ix_geocoding_cache_parcel
    ON geocoding_cache(resolved_parcel_id)
    WHERE resolved_parcel_id IS NOT NULL;

-- --------------------------------------------------------------------------
-- 8. ACTIVIDADES
-- --------------------------------------------------------------------------
CREATE TABLE activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    category TEXT,
    mapping_status TEXT NOT NULL DEFAULT 'official'
        CHECK (mapping_status IN ('official', 'provisional', 'deprecated')),
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id)
);

CREATE TABLE activity_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL
        REFERENCES activities(id)
        ON DELETE CASCADE,
    alias TEXT NOT NULL,
    normalized_alias TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'provisional'
        CHECK (status IN ('official', 'provisional', 'deprecated')),
    source_version_id BIGINT
        REFERENCES source_versions(id),
    UNIQUE (activity_id, normalized_alias)
);

CREATE INDEX ix_activity_aliases_normalized
    ON activity_aliases(normalized_alias);

-- --------------------------------------------------------------------------
-- 9. MOTOR DETERMINÍSTICO DEL CUADRO DE USOS 3.3
-- --------------------------------------------------------------------------
CREATE TABLE activity_use_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL
        REFERENCES activities(id)
        ON DELETE CASCADE,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    mixtura SMALLINT NOT NULL
        CHECK (mixtura BETWEEN 1 AND 4),
    raw_value TEXT NOT NULL,
    status TEXT NOT NULL
        CHECK (status IN ('compatible', 'conditional', 'council_review', 'not_compatible')),
    min_surface_m2 NUMERIC(10,2),
    max_surface_m2 NUMERIC(10,2),
    exceeds_max_requires_council BOOLEAN NOT NULL DEFAULT FALSE,
    requires_street_width_min_m NUMERIC(8,2),
    requires_frontage_min_m NUMERIC(8,2),
    requires_frontage_max_m NUMERIC(8,2),
    special_condition TEXT,
    UNIQUE (activity_id, mixtura),
    CHECK (
        min_surface_m2 IS NULL
        OR max_surface_m2 IS NULL
        OR min_surface_m2 <= max_surface_m2
    )
);

-- --------------------------------------------------------------------------
-- 10. PROCEDIMIENTOS
-- --------------------------------------------------------------------------
CREATE TABLE procedures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id)
);

CREATE TABLE activity_procedures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL
        REFERENCES activities(id)
        ON DELETE CASCADE,
    procedure_id BIGINT NOT NULL
        REFERENCES procedures(id)
        ON DELETE CASCADE,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    priority INTEGER NOT NULL DEFAULT 100,
    UNIQUE (activity_id, procedure_id)
);

CREATE INDEX ix_activity_procedures_procedure
    ON activity_procedures(procedure_id);

CREATE TABLE procedure_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_procedure_id BIGINT NOT NULL
        REFERENCES activity_procedures(id)
        ON DELETE CASCADE,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    rule_type TEXT NOT NULL,
    priority INTEGER NOT NULL DEFAULT 100,
    min_surface_m2 NUMERIC(10,2),
    max_surface_m2 NUMERIC(10,2),
    conditions JSONB NOT NULL DEFAULT '{}'::jsonb,
    rationale TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (
        min_surface_m2 IS NULL
        OR max_surface_m2 IS NULL
        OR min_surface_m2 <= max_surface_m2
    )
);

CREATE INDEX ix_procedure_rules_activity_procedure
    ON procedure_rules(activity_procedure_id, priority);

CREATE TABLE procedure_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL
        REFERENCES procedures(id)
        ON DELETE CASCADE,
    requirement_code TEXT,
    title TEXT NOT NULL,
    description TEXT,
    conditional BOOLEAN NOT NULL DEFAULT FALSE,
    conditions JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    source_document_chunk_id BIGINT
);

CREATE UNIQUE INDEX uq_procedure_requirements_code
    ON procedure_requirements(procedure_id, requirement_code)
    WHERE requirement_code IS NOT NULL;

CREATE INDEX ix_procedure_requirements_procedure
    ON procedure_requirements(procedure_id);

CREATE TABLE procedure_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL
        REFERENCES procedures(id)
        ON DELETE CASCADE,
    document_code TEXT,
    title TEXT NOT NULL,
    description TEXT,
    conditional BOOLEAN NOT NULL DEFAULT FALSE,
    conditions JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    source_document_chunk_id BIGINT
);

CREATE UNIQUE INDEX uq_procedure_documents_code
    ON procedure_documents(procedure_id, document_code)
    WHERE document_code IS NOT NULL;

CREATE INDEX ix_procedure_documents_procedure
    ON procedure_documents(procedure_id);

CREATE TABLE procedure_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL
        REFERENCES procedures(id)
        ON DELETE CASCADE,
    step_order INTEGER NOT NULL CHECK (step_order > 0),
    title TEXT NOT NULL,
    description TEXT,
    source_version_id BIGINT NOT NULL
        REFERENCES source_versions(id),
    source_document_chunk_id BIGINT,
    UNIQUE (procedure_id, step_order)
);

-- --------------------------------------------------------------------------
-- 11. DOCUMENTOS Y RAG
-- --------------------------------------------------------------------------
-- Los archivos físicos permanecen fuera de PostgreSQL.
CREATE TABLE ai_models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL,
    model_name TEXT NOT NULL,
    model_type TEXT NOT NULL
        CHECK (model_type IN ('embedding', 'chat', 'reranker')),
    dimension INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (provider, model_name, model_type)
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_resource_id BIGINT NOT NULL
        REFERENCES source_resources(id)
        ON DELETE CASCADE,
    document_key TEXT NOT NULL,
    title TEXT NOT NULL,
    mime_type TEXT,
    page_count INTEGER,
    document_type TEXT NOT NULL DEFAULT 'other'
        CHECK (document_type IN ('normative', 'procedure', 'guide', 'form', 'annex', 'other')),
    authority_level TEXT NOT NULL DEFAULT 'unknown'
        CHECK (authority_level IN ('primary_normative', 'official_procedure', 'official_guidance', 'contextual', 'unknown')),
    UNIQUE (source_resource_id, document_key)
);

CREATE TABLE document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL
        REFERENCES documents(id)
        ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    heading_path TEXT,
    page_from INTEGER,
    page_to INTEGER,
    embedding halfvec(1024),
    embedding_model_id BIGINT
        REFERENCES ai_models(id),
    embedded_at TIMESTAMPTZ,
    embedding_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (embedding_status IN ('pending', 'processing', 'completed', 'failed')),
    embedding_claimed_at TIMESTAMPTZ,
    embedding_claim_token UUID,
    embedding_attempts INTEGER NOT NULL DEFAULT 0
        CHECK (embedding_attempts >= 0),
    embedding_error TEXT,
    UNIQUE (document_id, chunk_index),
    CHECK (
        embedding_status <> 'completed'
        OR embedding IS NOT NULL
    ),
    CHECK (
        page_from IS NULL
        OR page_to IS NULL
        OR page_from <= page_to
    )
);

CREATE INDEX ix_document_chunks_document
    ON document_chunks(document_id);

-- Búsqueda textual sin guardar una segunda columna derivada.
CREATE INDEX ix_document_chunks_tsv
    ON document_chunks
    USING GIN (to_tsvector('spanish', content));

CREATE INDEX ix_document_chunks_embedding_pending
    ON document_chunks(id)
    WHERE embedding IS NULL
      AND embedding_status IN ('pending', 'failed');

CREATE INDEX ix_document_chunks_embedding_claimed
    ON document_chunks(embedding_claimed_at)
    WHERE embedding_status = 'processing';

-- Índice vectorial: solo para filas que realmente tienen embedding.
CREATE INDEX ix_document_chunks_embedding_hnsw
    ON document_chunks
    USING HNSW (embedding halfvec_cosine_ops)
    WHERE embedding IS NOT NULL;

-- FK de la trazabilidad documental. Se declaran después de crear document_chunks.
ALTER TABLE procedure_requirements
    ADD CONSTRAINT fk_procedure_requirements_chunk
    FOREIGN KEY (source_document_chunk_id)
    REFERENCES document_chunks(id)
    ON DELETE SET NULL;

ALTER TABLE procedure_documents
    ADD CONSTRAINT fk_procedure_documents_chunk
    FOREIGN KEY (source_document_chunk_id)
    REFERENCES document_chunks(id)
    ON DELETE SET NULL;

ALTER TABLE procedure_steps
    ADD CONSTRAINT fk_procedure_steps_chunk
    FOREIGN KEY (source_document_chunk_id)
    REFERENCES document_chunks(id)
    ON DELETE SET NULL;

-- --------------------------------------------------------------------------
-- 12. TRAZA DE CONSULTAS
-- --------------------------------------------------------------------------
CREATE TABLE query_runs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    request_id UUID,
    question TEXT NOT NULL,
    activity_input TEXT,
    activity_id BIGINT
        REFERENCES activities(id)
        ON DELETE SET NULL,
    address_input TEXT,
    normalized_address TEXT,
    street_code INTEGER,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    surface_m2 NUMERIC(10,2),
    street_width_m NUMERIC(8,2),
    frontage_m NUMERIC(8,2),
    parcel_id BIGINT
        REFERENCES parcels(id)
        ON DELETE SET NULL,
    chat_model_id BIGINT
        REFERENCES ai_models(id)
        ON DELETE SET NULL,
    embedding_model_id BIGINT
        REFERENCES ai_models(id)
        ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'started'
        CHECK (status IN ('started', 'completed', 'partial', 'failed')),
    response_text TEXT,
    error_code TEXT,
    error_message TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    CHECK (completed_at IS NULL OR completed_at >= started_at)
);

CREATE UNIQUE INDEX uq_query_runs_request
    ON query_runs(request_id)
    WHERE request_id IS NOT NULL;

CREATE INDEX ix_query_runs_started
    ON query_runs(started_at DESC);

CREATE INDEX ix_query_runs_parcel
    ON query_runs(parcel_id)
    WHERE parcel_id IS NOT NULL;

CREATE TABLE query_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_run_id UUID NOT NULL
        REFERENCES query_runs(id)
        ON DELETE CASCADE,
    evidence_type TEXT NOT NULL,
    document_chunk_id BIGINT
        REFERENCES document_chunks(id)
        ON DELETE SET NULL,
    activity_use_rule_id BIGINT
        REFERENCES activity_use_rules(id)
        ON DELETE SET NULL,
    urban_parcel_rule_id BIGINT
        REFERENCES urban_parcel_rules(id)
        ON DELETE SET NULL,
    procedure_rule_id BIGINT
        REFERENCES procedure_rules(id)
        ON DELETE SET NULL,
    source_version_id BIGINT
        REFERENCES source_versions(id)
        ON DELETE SET NULL,
    score DOUBLE PRECISION,
    CHECK (
        document_chunk_id IS NOT NULL
        OR activity_use_rule_id IS NOT NULL
        OR urban_parcel_rule_id IS NOT NULL
        OR procedure_rule_id IS NOT NULL
        OR source_version_id IS NOT NULL
    )
);

CREATE INDEX ix_query_evidence_query
    ON query_evidence(query_run_id);

CREATE INDEX ix_query_evidence_source
    ON query_evidence(source_version_id)
    WHERE source_version_id IS NOT NULL;


-- SGI: mapping explícito Anexo II (Resolución 96/AGC/25) actividad -> tipo de trámite.
-- No sobrecarga activity_procedures: esta tabla conserva la clasificación de la fuente,
-- sus condiciones y el estado de revisión por código de actividad.

CREATE TABLE IF NOT EXISTS public.activity_tramite_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL
        REFERENCES public.activities(id)
        ON DELETE CASCADE,
    source_version_id BIGINT NOT NULL
        REFERENCES public.source_versions(id),
    activity_code_snapshot TEXT NOT NULL,
    catalog_activity_name_snapshot TEXT NOT NULL,
    annex_ii_activity_name_verified TEXT,
    procedure_type_code TEXT,
    procedure_type_label TEXT,
    possible_procedure_type_codes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    mapping_status TEXT NOT NULL
        CHECK (mapping_status IN (
            'confirmed',
            'conditional',
            'requires_review',
            'not_found_in_anexo_ii'
        )),
    mapping_method TEXT NOT NULL,
    annex_ii_page SMALLINT
        CHECK (annex_ii_page IS NULL OR annex_ii_page BETWEEN 1 AND 22),
    observations TEXT,
    source_annex_id TEXT NOT NULL,
    UNIQUE (activity_id, source_version_id),
    CHECK (
        procedure_type_code IS NULL
        OR procedure_type_code IN ('DDRR_E', 'DDRR_SP', 'DDRR_CP', 'LICENCIA')
    ),
    CHECK (
        possible_procedure_type_codes <@ ARRAY['DDRR_E', 'DDRR_SP', 'DDRR_CP', 'LICENCIA']::TEXT[]
    ),
    CHECK (
        (mapping_status = 'conditional' AND cardinality(possible_procedure_type_codes) >= 2)
        OR (mapping_status <> 'conditional' AND cardinality(possible_procedure_type_codes) = 0)
    ),
    CHECK (
        (procedure_type_code IS NOT NULL AND procedure_type_label IS NOT NULL)
        OR (procedure_type_code IS NULL AND procedure_type_label IS NULL)
    ),
    CHECK (
        (mapping_status = 'confirmed' AND procedure_type_code IS NOT NULL)
        OR (mapping_status <> 'confirmed' AND procedure_type_code IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_activity_tramite_mappings_activity
    ON public.activity_tramite_mappings (activity_id);

CREATE INDEX IF NOT EXISTS ix_activity_tramite_mappings_source_status
    ON public.activity_tramite_mappings (source_version_id, mapping_status);

CREATE INDEX IF NOT EXISTS ix_activity_tramite_mappings_type
    ON public.activity_tramite_mappings (procedure_type_code)
    WHERE procedure_type_code IS NOT NULL;
